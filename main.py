def ensure_embedded_template():
    default_template = DATA / 'base_template.py'
    try:
        payload = gzip.decompress(base64.b64decode(''.join(_EMBEDDED_TEMPLATE_GZIP_B64)))
        default_template.write_bytes(payload)
    except Exception as exc:
        raise RuntimeError(f'Could not restore embedded base bot template: {exc}') from exc
    return default_template


def init_db():
    default_template = ensure_embedded_template()
    with db() as c:
        c.execute('''CREATE TABLE IF NOT EXISTS users(
            user_id INTEGER PRIMARY KEY, first_name TEXT, username TEXT, joined_at TEXT)''')
        c.execute('''CREATE TABLE IF NOT EXISTS clones(
            id INTEGER PRIMARY KEY AUTOINCREMENT, owner_id INTEGER NOT NULL,
            bot_id INTEGER NOT NULL UNIQUE, bot_username TEXT, bot_name TEXT,
            workdir TEXT NOT NULL, pid INTEGER, status TEXT NOT NULL DEFAULT 'stopped',
            created_at TEXT NOT NULL)''')
        c.execute("CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        # Persist the selected clone because FSM memory may be lost on restart.
        c.execute("CREATE TABLE IF NOT EXISTS admin_sessions("
                  "admin_id INTEGER PRIMARY KEY, clone_id INTEGER NOT NULL, updated_at TEXT NOT NULL)")
        c.execute("INSERT OR IGNORE INTO settings(key,value) VALUES('clone_limit','1')")
        c.execute("INSERT OR REPLACE INTO settings(key,value) VALUES('template_path',?)", (str(default_template),))


