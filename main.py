async def _send_message_bold(*args, **kwargs):
    if 'text' in kwargs and isinstance(kwargs['text'], str):
        kwargs['text'] = f"<b>{kwargs['text']}</b>"
    elif len(args) > 1 and isinstance(args[1], str):
        args = (args[0], f"<b>{args[1]}</b>", *args[2:])
    return await _original_send_message(*args, **kwargs)

async def _edit_message_text_bold(*args, **kwargs):
    if 'text' in kwargs and isinstance(kwargs['text'], str):
        kwargs['text'] = f"<b>{kwargs['text']}</b>"
    elif len(args) > 2 and isinstance(args[2], str):
        args = (*args[:2], f"<b>{args[2]}</b>", *args[3:])
    return await _original_edit_message_text(*args, **kwargs)

