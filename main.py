# CENTRAL ADMIN PANEL — runs inside the Cloning Bot and operates on the
# selected clone's own Cuibcc.db. All queries are parameterized and tenant
# access is checked on every callback/message.
# -----------------------------------------------------------------------------
def clone_db_path(clone_id: int):
    row = get_clone(clone_id)
    if not row:
        return None
    return Path(row['workdir']) / 'Cuibcc.db'


def tenant_conn(clone_id: int):
    path = clone_db_path(clone_id)
    if not path or not path.exists():
        raise RuntimeError('This bot database is not ready yet. Start the bot and try again.')
    con = sqlite3.connect(path)
    con.row_factory = sqlite3.Row
    return con


def can_manage_clone(uid: int, clone_id: int):
    row = get_clone(clone_id)
    return bool(row and (row['owner_id'] == uid or is_owner(uid)))


def central_admin_kb(clone_id: int):
    return InlineKeyboardMarkup(inline_keyboard=[
        [InlineKeyboardButton(text='📦 Products', callback_data=f'ca:products:{clone_id}', style='success'), InlineKeyboardButton(text='👥 Users', callback_data=f'ca:users:{clone_id}', style='primary')],
        [InlineKeyboardButton(text='🧾 Orders', callback_data=f'ca:orders:{clone_id}', style='primary'), InlineKeyboardButton(text='🎫 Tickets', callback_data=f'ca:tickets:{clone_id}', style='primary')],
        [InlineKeyboardButton(text='📊 Store Statistics', callback_data=f'ca:stats:{clone_id}', style='success')],
        [InlineKeyboardButton(text='⬅️ Back to Bot', callback_data=f'select:{clone_id}', style='danger')],
    ])


async def open_central_admin(call: CallbackQuery, clone_id: int, state: FSMContext = None):
    if not can_manage_clone(call.from_user.id, clone_id):
        return await call.answer('Not authorized.', show_alert=True)
    if not _template_router_loaded or not _template_admin_module:
        return await call.answer('Original admin panel could not be loaded. Check the base template.', show_alert=True)
    save_admin_session(call.from_user.id, clone_id)
    if state is not None:
        await state.clear()
        await state.set_state(None)
        await state.update_data(_central_admin_clone_id=clone_id)

    # The original template's admin_kb() may read settings from its SQLite DB.
    # Build that first keyboard while the selected tenant context is active;
    # otherwise current_tenant_db() raises "No clone selected" on first open.
    clone_token = _active_template_clone.set(clone_id)
    admin_token = _active_template_admin.set(call.from_user.id)
    try:
        admin_markup = _template_admin_module['admin_kb']()
    finally:
        _active_template_admin.reset(admin_token)
        _active_template_clone.reset(clone_token)

    await call.message.edit_text(
        '⚙️ <b>Advanced Admin Terminal</b>\n<i>Authorized Access Granted.</i>',
        reply_markup=admin_markup,
        parse_mode='HTML')
    await call.answer()


@dp.callback_query(lambda q: bool(q.data) and q.data.startswith('ca:') and not q.data.startswith(('ca:addbal:', 'ca:minusbal:')))
async def central_admin_routes(call: CallbackQuery, state: FSMContext):
    try:
        parts = call.data.split(':')
        action = parts[1]
        clone_id = int(parts[2])
    except Exception:
        return await call.answer('Invalid request.', show_alert=True)
    if not can_manage_clone(call.from_user.id, clone_id):
        return await call.answer('Not authorized.', show_alert=True)
    try:
        with tenant_conn(clone_id) as con:
            if action == 'home':
                return await open_central_admin(call, clone_id)
            if action == 'stats':
                u = con.execute('SELECT COUNT(*) n FROM users').fetchone()['n']
                p = con.execute('SELECT COUNT(*) n FROM products').fetchone()['n']
                o = con.execute('SELECT COUNT(*) n FROM orders').fetchone()['n']
                bal = con.execute('SELECT COALESCE(SUM(balance),0) n FROM users').fetchone()['n']
                await call.message.edit_text(f'<b>📊 STORE STATISTICS</b>\nUsers: <b>{u}</b>\nProducts: <b>{p}</b>\nOrders: <b>{o}</b>\nWallet liability: <b>₹{bal:.2f}</b>', reply_markup=central_admin_kb(clone_id))
            elif action == 'products':
                rows = con.execute('SELECT id,name,price_inr,is_active FROM products ORDER BY id DESC LIMIT 30').fetchall()
                buttons = [[InlineKeyboardButton(text=f"{'🟢' if r['is_active'] else '🔴'} {str(r['name'])[:28]} · ₹{r['price_inr']}", callback_data=f'ca:product:{clone_id}:{r["id"]}', style='primary')] for r in rows]
                buttons += [[InlineKeyboardButton(text='➕ Add Product', callback_data=f'ca:addproduct:{clone_id}', style='success')], [InlineKeyboardButton(text='⬅️ Admin Home', callback_data=f'ca:home:{clone_id}', style='danger')]]
                await call.message.edit_text('<b>📦 PRODUCT MANAGEMENT</b>\nSelect a product:', reply_markup=InlineKeyboardMarkup(inline_keyboard=buttons))
            elif action == 'product':
                parts = call.data.split(':'); pid = int(parts[3])
                r = con.execute('SELECT * FROM products WHERE id=?', (pid,)).fetchone()
                if not r: return await call.answer('Product not found.', show_alert=True)
                txt = (f'<b>📦 {escape(str(r["name"]))}</b>\nID: <code>{pid}</code>\nCategory: {escape(str(r["category"]))}\nPrice: ₹{r["price_inr"]}\nStock: {r["stock"]}\nStatus: {"Active" if r["is_active"] else "Hidden"}')
                kb = InlineKeyboardMarkup(inline_keyboard=[
                    [InlineKeyboardButton(text='✏️ Edit Name', callback_data=f'ca:editname:{clone_id}:{pid}', style='primary'), InlineKeyboardButton(text='💰 Edit Price', callback_data=f'ca:editprice:{clone_id}:{pid}', style='primary')],
                    [InlineKeyboardButton(text='📥 Add Stock Keys', callback_data=f'ca:addkeys:{clone_id}:{pid}', style='success')],
                    [InlineKeyboardButton(text='👁 Toggle Visibility', callback_data=f'ca:toggle:{clone_id}:{pid}', style='success')],
                    [InlineKeyboardButton(text='🗑 Delete Product', callback_data=f'ca:delete:{clone_id}:{pid}', style='danger')],
                    [InlineKeyboardButton(text='⬅️ Products', callback_data=f'ca:products:{clone_id}', style='danger')],
                ])
                await call.message.edit_text(txt, reply_markup=kb)
            elif action in ('editname','editprice'):
                parts = call.data.split(':'); pid = int(parts[3])
                await state.set_state(CentralAdminFlow.product_value)
                await state.update_data(clone_id=clone_id, product_id=pid, edit_field=action)
                await call.message.edit_text('Send the new product name:' if action == 'editname' else 'Send the new price in INR (number only):', reply_markup=InlineKeyboardMarkup(inline_keyboard=[[InlineKeyboardButton(text='Cancel', callback_data=f'ca:product:{clone_id}:{pid}', style='danger')]]))
            elif action == 'toggle':
                pid = int(call.data.split(':')[3]); con.execute('UPDATE products SET is_active=CASE WHEN is_active=1 THEN 0 ELSE 1 END WHERE id=?',(pid,)); con.commit()
                call.data=f'ca:product:{clone_id}:{pid}'
                return await central_admin_routes(call, state)
            elif action == 'delete':
                pid = int(call.data.split(':')[3]); con.execute('DELETE FROM product_keys WHERE product_id=?',(pid,)); con.execute('DELETE FROM products WHERE id=?',(pid,)); con.commit()
                call.data=f'ca:products:{clone_id}'
                return await central_admin_routes(call, state)
            elif action == 'addkeys':
                pid = int(call.data.split(':')[3])
                await state.set_state(CentralAdminFlow.add_keys)
                await state.update_data(clone_id=clone_id, product_id=pid)
                await call.message.edit_text('Send stock keys, one key per line:')
            elif action == 'addproduct':
                await state.set_state(CentralAdminFlow.add_category)
                await state.update_data(clone_id=clone_id)
                await call.message.edit_text('Send the new product category name:')
            elif action == 'users':
                await state.set_state(CentralAdminFlow.user_lookup)
                await state.update_data(clone_id=clone_id)
                await call.message.edit_text('Send a user Telegram ID to look up:')
            elif action == 'orders':
                rows = con.execute('SELECT id,user_id,product_name,price_paid,purchase_date FROM orders ORDER BY id DESC LIMIT 15').fetchall()
                text_rows = [f'#{r["id"]} · UID <code>{r["user_id"]}</code> · {escape(str(r["product_name"]))} · ₹{r["price_paid"]} · {escape(str(r["purchase_date"]))}' for r in rows]
                await call.message.edit_text('<b>🧾 RECENT ORDERS</b>\n\n' + ('\n'.join(text_rows) if text_rows else 'No orders yet.'), reply_markup=central_admin_kb(clone_id))
            elif action == 'tickets':
                rows = con.execute("SELECT id,user_id,message,created_at FROM tickets WHERE status='Open' ORDER BY id DESC LIMIT 10").fetchall()
                buttons = [[InlineKeyboardButton(text=f'Ticket #{r["id"]} · UID {r["user_id"]}', callback_data=f'ca:ticket:{clone_id}:{r["id"]}', style='primary')] for r in rows]
                buttons.append([InlineKeyboardButton(text='⬅️ Admin Home', callback_data=f'ca:home:{clone_id}', style='danger')])
                await call.message.edit_text('<b>🎫 OPEN TICKETS</b>\nSelect a ticket:', reply_markup=InlineKeyboardMarkup(inline_keyboard=buttons))
            elif action == 'ticket':
                tid = int(call.data.split(':')[3]); r = con.execute('SELECT id,user_id,message,created_at FROM tickets WHERE id=?',(tid,)).fetchone()
                if not r: return await call.answer('Ticket not found.', show_alert=True)
                await state.set_state(CentralAdminFlow.ticket_reply); await state.update_data(clone_id=clone_id,ticket_id=tid,user_id=r['user_id'])
                await call.message.edit_text(f'<b>🎫 Ticket #{tid}</b>\nUser: <code>{r["user_id"]}</code>\n\n{escape(str(r["message"] or "[attachment]"))}\n\nSend your reply as a message:')
        await call.answer()
    except Exception as e:
        log.exception('Central admin action failed')
        await call.answer(f'Admin error: {str(e)[:130]}', show_alert=True)


@dp.message(CentralAdminFlow.product_value)
async def central_product_value(message: Message, state: FSMContext):
    d=await state.get_data(); cid=int(d['clone_id']); pid=int(d['product_id']); field=d['edit_field']
    if not can_manage_clone(message.from_user.id,cid): return await state.clear()
    value=(message.text or '').strip()
    try:
        with tenant_conn(cid) as con:
            if field=='editprice':
                price=float(value)
                if price<0: raise ValueError
                con.execute('UPDATE products SET price_inr=? WHERE id=?',(price,pid))
            else:
                if not value or len(value)>120: raise ValueError
                con.execute('UPDATE products SET name=? WHERE id=?',(value,pid))
            con.commit()
        await state.clear(); await message.answer('✅ Product updated. Open My Bots → Admin Panel to continue.')
    except Exception:
        await message.answer('Invalid value. Please send a valid name or non-negative price.')


@dp.message(CentralAdminFlow.add_keys)
async def central_add_keys(message: Message, state: FSMContext):
    d=await state.get_data(); cid=int(d['clone_id']); pid=int(d['product_id'])
    keys=[x.strip() for x in (message.text or '').splitlines() if x.strip()]
