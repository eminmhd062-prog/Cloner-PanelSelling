@dp.message(CentralAdminFlow.ticket_reply)
async def central_ticket_reply(message: Message, state: FSMContext):
    d=await state.get_data(); cid=int(d['clone_id']); uid=int(d['user_id']); tid=int(d['ticket_id'])
    if not can_manage_clone(message.from_user.id,cid): return await state.clear()
    row=get_clone(cid)
    try:
        # Use the clone bot token to deliver the reply to the customer.
        envfile=Path(row['workdir'])/'.env'; token=''
        for line in envfile.read_text().splitlines():
            if line.startswith('BOT_TOKEN='): token=line.split('=',1)[1]
        customer_bot=Bot(token)
        await customer_bot.send_message(uid, f'💬 <b>Support reply — Ticket #{tid}</b>\n\n{escape(message.text or "")}', parse_mode='HTML')
        await customer_bot.session.close()
        with tenant_conn(cid) as con:
            con.execute("UPDATE tickets SET status='Closed' WHERE id=?",(tid,)); con.commit()
        await state.clear(); await message.answer('✅ Reply delivered and ticket closed.')
    except Exception as e: await message.answer(f'Could not deliver reply: {escape(str(e)[:140])}')


