    fields = getattr(_InlineKeyboardButton, 'model_fields', {}) or getattr(_InlineKeyboardButton, '__fields__', {})
    if style and 'style' in fields:
        kwargs['style'] = style
    return _InlineKeyboardButton(**kwargs)

