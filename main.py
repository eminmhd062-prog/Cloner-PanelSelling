# ORIGINAL TEMPLATE ADMIN PANEL BRIDGE
# The uploaded template's own admin handlers are registered on a child Router.
# Each interaction is scoped to the selected clone's database and owner.
# -----------------------------------------------------------------------------
_active_template_clone = ContextVar('active_template_clone', default=None)
_active_template_admin = ContextVar('active_template_admin', default=None)
_active_template_bot = ContextVar('active_template_bot', default=None)
_template_admin_module = None
_template_router_loaded = False
_template_module_loading = False


def current_tenant_db():
    clone_id = _active_template_clone.get()
    if clone_id is None:
        # The original template evaluates a few UI constants at import time
        # (for example get_emoji() inside UI_TEXTS). Those reads happen before
        # a user has selected a clone, so route ONLY import-time reads to an
        # isolated empty bootstrap DB. Runtime admin actions still require a
        # selected tenant and can never fall back to this database.
        if _template_module_loading:
            return str(DATA / 'template_import_bootstrap.db')
        raise RuntimeError('No clone selected for template admin action.')
    row = get_clone(int(clone_id))
    if not row:
        raise RuntimeError('Selected clone no longer exists.')
    return str(Path(row['workdir']) / 'Cuibcc.db')


def tenant_admin_id():
    value = _active_template_admin.get()
    return int(value) if value is not None else -1


async def clear_template_state(state):
    """Clear a template admin form while retaining the selected clone context."""
    data = await state.get_data()
    clone_id = data.get('_central_admin_clone_id')
    await state.clear()
    if clone_id is not None:
        await state.update_data(_central_admin_clone_id=clone_id)


class TemplateBotProxy:
    """Use the central bot for admin UI and the selected clone bot for customer DMs."""
    async def send_message(self, chat_id, *args, **kwargs):
        admin_id = _active_template_admin.get()
        if admin_id is not None and int(chat_id) == int(admin_id):
            return await bot.send_message(chat_id, *args, **kwargs)
        clone_bot = _active_template_bot.get()
        if clone_bot is None:
            raise RuntimeError('No selected clone bot is available for this action.')
        return await clone_bot.send_message(chat_id, *args, **kwargs)


class TemplateTenantMiddleware:
    async def __call__(self, handler, event, data):
        user = getattr(event, 'from_user', None)
        if user is None:
            return await handler(event, data)

        # Prefer FSM data; fall back to persistent selection after restarts.
        state = data.get('state')
        raw_clone_id = None
        if state is not None:
            try:
                state_data = await state.get_data()
                raw_clone_id = state_data.get('_central_admin_clone_id')
            except Exception:
                log.exception('Could not read admin FSM context')
        try:
            clone_id = int(raw_clone_id) if raw_clone_id else get_admin_session(user.id)
        except (TypeError, ValueError):
            clone_id = get_admin_session(user.id)
        if not clone_id:
            if isinstance(event, CallbackQuery):
                await event.answer('Please reopen My Bots → Admin Panel to select a bot.', show_alert=True)
            elif isinstance(event, Message):
                await event.answer('Please open My Bots → Admin Panel first.')
            return
        row = get_clone(clone_id)
        uid = event.from_user.id
        if not row or (row['owner_id'] != uid and not is_owner(uid)):
            if isinstance(event, CallbackQuery):
                await event.answer('Not authorized for this bot.', show_alert=True)
            elif isinstance(event, Message):
                await event.answer('Not authorized for this bot.')
            return

        env_path = Path(row['workdir']) / '.env'
        token = ''
        try:
            for line in env_path.read_text(encoding='utf-8').splitlines():
                if line.startswith('BOT_TOKEN='):
                    token = line.split('=', 1)[1].strip()
                    break
        except OSError:
            token = ''
        if not token:
            if isinstance(event, CallbackQuery):
                await event.answer('Clone token configuration is missing.', show_alert=True)
            elif isinstance(event, Message):
                await event.answer('Clone token configuration is missing.')
            return

        clone_bot = Bot(token=token, default=DefaultBotProperties(parse_mode='HTML'))
        t_clone = _active_template_clone.set(clone_id)
        t_admin = _active_template_admin.set(uid)
        t_bot = _active_template_bot.set(clone_bot)
        try:
            return await handler(event, data)
        finally:
            _active_template_clone.reset(t_clone)
            _active_template_admin.reset(t_admin)
            _active_template_bot.reset(t_bot)
            await clone_bot.session.close()


def build_template_admin_router():
    """Load the exact admin UI/handlers from the active base template."""
    global _template_admin_module, _template_router_loaded
    if _template_router_loaded:
        return
    template_path = load_template()
    source = template_path.read_text(encoding='utf-8')
    # This bridge currently targets the uploaded aiogram template structure.
    if 'from aiogram import Bot, Dispatcher, F, BaseMiddleware' not in source:
        raise RuntimeError('The uploaded template is not the supported aiogram template format.')
    source = source.replace(
        'from aiogram import Bot, Dispatcher, F, BaseMiddleware',
        'from aiogram import Bot, Dispatcher, Router, F, BaseMiddleware', 1)
    source = source.replace(
        '    InlineKeyboardMarkup, InlineKeyboardButton, CallbackQuery, Message, Dice, BufferedInputFile',
        '    InlineKeyboardMarkup, InlineKeyboardButton as _RawInlineKeyboardButton, CallbackQuery, Message, Dice, BufferedInputFile', 1)
    source = source.replace('dp = Dispatcher()', 'dp = Router()', 1)
    source = source.replace(
        'bot = Bot(token=BOT_TOKEN, default=DefaultBotProperties(parse_mode="HTML"))',
        'bot = _template_bot_proxy', 1)
    source = source.replace(
        'bot = ThemedBot(token=BOT_TOKEN, default=DefaultBotProperties(parse_mode="HTML"))',
        'bot = _template_bot_proxy', 1)
    source = re.sub(r"sqlite3\.connect\(['\"]Cuibcc\.db['\"]\)", 'sqlite3.connect(current_tenant_db())', source)

    # Do not execute the template's own polling entry point in the manager process.
    boot_marker = '# 25. BOOTSTRAPPING & MAIN'
    if boot_marker in source:
        source = source.split(boot_marker, 1)[0]

    # Use the selected clone owner as the template's ADMIN_ID for this update.
    lines = []
    for line in source.splitlines():
        if re.match(r'^ADMIN_ID\s*=', line):
            lines.append('ADMIN_ID = 0  # replaced by tenant_admin_id() below')
        else:
            lines.append(re.sub(r'\bADMIN_ID\b', 'tenant_admin_id()', line))
    source = '\n'.join(lines) + '\n'
    source = source.replace('await state.clear()', 'await clear_template_state(state)')

    # Provide a version-tolerant InlineKeyboardButton constructor for Bot API styles.
    wrapper = "\n\ndef InlineKeyboardButton(**kwargs):\n    style = kwargs.pop('style', None)\n    fields = getattr(_RawInlineKeyboardButton, 'model_fields', {}) or getattr(_RawInlineKeyboardButton, '__fields__', {})\n    if style and 'style' in fields:\n        kwargs['style'] = style\n    allowed = set(fields) if fields else None\n    if allowed is not None:\n        kwargs = {k: v for k, v in kwargs.items() if k in allowed}\n    return _RawInlineKeyboardButton(**kwargs)\n\n"
    # Add wrapper after the aiogram.types import block.
    import_start = source.find('from aiogram.types import (')
    import_close = source.find('\n)', import_start) if import_start >= 0 else -1
    if import_close >= 0:
        idx = import_close + 2
        source = source[:idx] + wrapper + source[idx:]
    source = source.replace('bot = _template_bot_proxy', 'bot = _template_bot_proxy', 1)

    template_router = Router()
    namespace = {
        '__name__': 'centralized_panel_template',
        '_template_bot_proxy': TemplateBotProxy(),
        'current_tenant_db': current_tenant_db,
        'tenant_admin_id': tenant_admin_id,
        'clear_template_state': clear_template_state,
    }
    # Execute only the owner-provided template in this isolated namespace.
    # The source reads settings while importing module-level UI constants.
    # Prepare an isolated bootstrap database with the same settings table so
    # these harmless reads do not emit missing-table errors.
    bootstrap_db = DATA / 'template_import_bootstrap.db'
    with sqlite3.connect(bootstrap_db) as bootstrap:
        bootstrap.execute(
            "CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT NOT NULL)")
        bootstrap.execute(
            "INSERT OR IGNORE INTO settings(key,value) VALUES('emoji_info','')")
        bootstrap.execute(
            "INSERT OR IGNORE INTO settings(key,value) VALUES('emoji_check','')")
    global _template_module_loading
    _template_module_loading = True
    try:
        exec(compile(source, str(template_path), 'exec'), namespace)
    finally:
        _template_module_loading = False
    template_router = namespace['dp']
    # Run after FSM middleware has populated `state` in handler data. The
    # template admin callbacks use ordinary callback_data (without clone IDs),
    # so the selected clone must be recovered from this user's FSM data.
    # Registering this as outer middleware runs before FSMContext is available
    # on some aiogram 3 versions and silently prevents every admin handler.
    # In aiogram 3.x, observer.middleware is the inner middleware manager;
    # TelegramEventObserver has no inner_middleware() method.
    template_router.message.middleware.register(TemplateTenantMiddleware())
    template_router.callback_query.middleware.register(TemplateTenantMiddleware())
    dp.include_router(template_router)
    _template_admin_module = namespace
    _template_router_loaded = True


